let currentLanguage = localStorage.getItem("arr_lang") || "English";
if (!i18nData[currentLanguage]) currentLanguage = "English";

function t(key) {
  const dict = i18nData[currentLanguage] || i18nData.English;
  return dict[key] || i18nData.English[key] || key;
}

function setLanguage(lang) {
  if (i18nData[lang]) {
    currentLanguage = lang;
    localStorage.setItem("arr_lang", lang);
    document.documentElement.lang = lang === "Hindi" ? "hi" : "en";
  }
}

function toggleLanguage() {
  const next = currentLanguage === "English" ? "Hindi" : "English";
  setLanguage(next);
  return next;
}
